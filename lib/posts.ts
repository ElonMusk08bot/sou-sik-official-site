如果你徹底清潔刀盤區、出粉路徑與接粉杯後，表現立刻大幅恢復，問題更可能是殘粉、油脂或結塊，不一定是刀盤磨損。

反過來說，如果你已經完成清潔、歸零、重新對位，表現仍然持續偏離，刀盤本身的磨耗機率就提高。

